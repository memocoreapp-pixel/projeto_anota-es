/** Retorna um elemento pelo id. */
export function getElementById(id: string): Element | undefined {
  return elements.find((element) => element.id === id);
}

/** Retorna vários elementos a partir de uma lista de ids (na ordem dada). */
export function getElementsByIds(ids: string[]): Element[] {
  return ids
    .map((id) => getElementById(id))
    .filter((element): element is Element => Boolean(element));
}
